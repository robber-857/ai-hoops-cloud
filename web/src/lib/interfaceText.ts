export function interfaceText(language: AppLanguage, text: string, ...values: (string | number)[]): string {
  const message = language === "zh-CN" && Object.hasOwn(simplifiedChinese, text) ? simplifiedChinese[text] : text;
  return values.length ? message.replace(/\{(\d+)\}/g, (token, index) => String(values[Number(index)] ?? token)) : message;
}
